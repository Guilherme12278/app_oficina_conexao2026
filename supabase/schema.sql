-- Execute no SQL Editor do projeto Supabase.
create table if not exists public.teste_nomes (
  id bigint generated by default as identity primary key,
  nome text not null check (char_length(trim(nome)) between 1 and 100),
  criado_em timestamptz not null default now()
);

alter table public.teste_nomes enable row level security;

-- Protótipo: permite somente INSERT anônimo, sem leitura pública dos registros.
grant insert on table public.teste_nomes to anon;
grant usage, select on sequence public.teste_nomes_id_seq to anon;

drop policy if exists "Permitir cadastro de nomes no prototipo" on public.teste_nomes;
create policy "Permitir cadastro de nomes no prototipo"
on public.teste_nomes
for insert
to anon
with check (char_length(trim(nome)) between 1 and 100);
